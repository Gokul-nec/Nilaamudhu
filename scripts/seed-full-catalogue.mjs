async function seed() {
  console.log("Syncing categories...");
  const catMap = new Map();

  for (const cat of categoriesDef) {
    const snap = await db.collection("categories").where("slug", "==", cat.slug).get();
    if (!snap.empty) {
      const id = snap.docs[0].id;
      catMap.set(cat.slug, id);
      await db.collection("categories").doc(id).set({
        ...cat,
        is_active: true,
        updated_at: new Date().toISOString(),
      }, { merge: true });
      console.log(`Updated category: ${cat.name_en} (${id})`);
    } else {
      const ref = await db.collection("categories").add({
        ...cat,
        image_path: null,
        is_active: true,
        created_at: new Date().toISOString(),
        updated_at: new Date().toISOString(),
      });
      catMap.set(cat.slug, ref.id);
      console.log(`Created category: ${cat.name_en} (${ref.id})`);
    }
  }

  console.log("\nSyncing products (35 items) without duplicates...");
  let addedCount = 0;
  let updatedCount = 0;

  for (const item of catalogue) {
    const category_id = catMap.get(item.category_slug) || null;
    const { category_slug, ...productData } = item;

    const existingSnap = await db.collection("products").where("slug", "==", productData.slug).get();

    const payload = {
      ...productData,
      category_id,
      images: [],
      updated_at: new Date().toISOString(),
    };

    if (!existingSnap.empty) {
      const docId = existingSnap.docs[0].id;
      await db.collection("products").doc(docId).set(payload, { merge: true });
      updatedCount++;
      console.log(`Updated: ${productData.name_en}`);
    } else {
      await db.collection("products").add({
        ...payload,
        created_at: new Date().toISOString(),
      });
      addedCount++;
      console.log(`Added: ${productData.name_en}`);
    }
  }

  console.log(`\nCatalogue sync complete! Added: ${addedCount}, Updated: ${updatedCount}, Total: ${catalogue.length}`);
  process.exit(0);
}

seed().catch((err) => {
  console.error("Seeding failed:", err);
  process.exit(1);
});
